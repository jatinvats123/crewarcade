// Object storage for game HTML (and later clips/uploads). Three drivers behind one interface:
//   supabase: Supabase Storage REST API with the service-role key (production; private `games`
//             bucket, read back only by our server, which serves games with strict headers);
//   local:    files under GAMES_LOCAL_DIR (development only: config refuses production without
//             Supabase, because Render's disk is wiped on every deploy);
//   memory:   a Map (tests).
// Keys look like "<slug>/v<N>/index.html"; the stored path (game_versions.html_path) is
// "<bucket>/<key>", e.g. "games/chai-dash/v1/index.html".
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Config } from '../config';

export interface ObjectStorage {
  readonly kind: 'supabase' | 'local' | 'memory';
  readonly bucket: string;
  put(key: string, body: string | Buffer, contentType: string): Promise<string>;
  /** null when the object does not exist. */
  get(key: string): Promise<Buffer | null>;
  /** Creates the private bucket when missing (idempotent). */
  ensureBucket(): Promise<void>;
}

/** "<slug>/v<N>/index.html" for one game version. */
export const gameHtmlKey = (slug: string, version: number): string => `${slug}/v${version}/index.html`;
/** Glitch's playtest media in the `clips` bucket: the GIF and the mid-game screenshot. */
export const CLIP_FILES = { gif: 'play.gif', shot: 'shot.png' } as const;
export const clipKey = (slug: string, version: number, file: keyof typeof CLIP_FILES): string => `${slug}/v${version}/${CLIP_FILES[file]}`;
/** Public URL of a clip, served by our server (GET /clips/...) whatever the storage driver. */
export const clipUrl = (apiOrigin: string, slug: string, version: number, file: keyof typeof CLIP_FILES): string =>
  `${apiOrigin.replace(/\/+$/, '')}/clips/${clipKey(slug, version, file)}`;

const KEY_RE = /^[a-z0-9][a-z0-9-]{0,62}(\/[A-Za-z0-9._-]{1,64}){1,4}$/;
/** Keys are generated by us; this still refuses traversal or odd characters. */
export function assertKey(key: string): void {
  if (!KEY_RE.test(key) || key.split('/').some(p => p === '.' || p === '..')) throw new Error(`invalid storage key: ${key}`);
}

export class StorageError extends Error {}

type FetchFn = (
  url: string,
  init: { method: string; headers: Record<string, string>; body?: string | Buffer | Uint8Array },
) => Promise<{
  status: number;
  arrayBuffer(): Promise<ArrayBuffer>;
  text(): Promise<string>;
}>;

export function createSupabaseStorage(o: { url: string; serviceKey: string; bucket: string; public?: boolean; fetch?: FetchFn }): ObjectStorage {
  const base = `${o.url.replace(/\/+$/, '')}/storage/v1`;
  const doFetch: FetchFn = o.fetch ?? ((u, i) => fetch(u, i as RequestInit));
  const auth = { Authorization: `Bearer ${o.serviceKey}`, apikey: o.serviceKey };
  return {
    kind: 'supabase',
    bucket: o.bucket,
    async put(key, body, contentType) {
      assertKey(key);
      const res = await doFetch(`${base}/object/${o.bucket}/${key}`, {
        method: 'POST',
        headers: { ...auth, 'Content-Type': contentType, 'x-upsert': 'true', 'Cache-Control': 'max-age=31536000' },
        body: typeof body === 'string' ? Buffer.from(body, 'utf8') : body,
      });
      if (res.status >= 300) throw new StorageError(`storage upload failed (${res.status}): ${(await res.text()).slice(0, 200)}`);
      return `${o.bucket}/${key}`;
    },
    async get(key) {
      assertKey(key);
      const res = await doFetch(`${base}/object/authenticated/${o.bucket}/${key}`, { method: 'GET', headers: auth });
      if (res.status === 404 || res.status === 400) return null;
      if (res.status >= 300) throw new StorageError(`storage download failed (${res.status})`);
      return Buffer.from(await res.arrayBuffer());
    },
    async ensureBucket() {
      const res = await doFetch(`${base}/bucket`, {
        method: 'POST',
        headers: { ...auth, 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: o.bucket, name: o.bucket, public: o.public ?? false }),
      });
      // 200 created; 400/409 "already exists".
      if (res.status >= 300 && res.status !== 400 && res.status !== 409) throw new StorageError(`bucket check failed (${res.status})`);
    },
  };
}

export function createLocalStorage(o: { dir: string; bucket: string }): ObjectStorage {
  const root = path.resolve(o.dir);
  const file = (key: string) => {
    assertKey(key);
    const f = path.resolve(root, key);
    if (!f.startsWith(root + path.sep)) throw new Error(`invalid storage key: ${key}`);
    return f;
  };
  return {
    kind: 'local',
    bucket: o.bucket,
    async put(key, body) {
      const f = file(key);
      await mkdir(path.dirname(f), { recursive: true });
      await writeFile(f, body);
      return `${o.bucket}/${key}`;
    },
    async get(key) {
      try {
        return await readFile(file(key));
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
        throw e;
      }
    },
    async ensureBucket() {
      await mkdir(root, { recursive: true });
    },
  };
}

export function createMemoryStorage(bucket = 'games'): ObjectStorage & { objects: Map<string, Buffer> } {
  const objects = new Map<string, Buffer>();
  return {
    kind: 'memory',
    bucket,
    objects,
    async put(key, body) {
      assertKey(key);
      objects.set(key, typeof body === 'string' ? Buffer.from(body, 'utf8') : body);
      return `${bucket}/${key}`;
    },
    async get(key) {
      assertKey(key);
      return objects.get(key) ?? null;
    },
    async ensureBucket() {},
  };
}

/** Production: Supabase or a hard error (never the local disk). Development: local disk fallback. */
export function createGameStorage(
  config: Pick<Config, 'NODE_ENV' | 'SUPABASE_URL' | 'SUPABASE_SERVICE_ROLE_KEY' | 'SUPABASE_GAMES_BUCKET' | 'GAMES_LOCAL_DIR'>,
): ObjectStorage {
  if (config.SUPABASE_URL && config.SUPABASE_SERVICE_ROLE_KEY)
    return createSupabaseStorage({ url: config.SUPABASE_URL, serviceKey: config.SUPABASE_SERVICE_ROLE_KEY, bucket: config.SUPABASE_GAMES_BUCKET });
  if (config.NODE_ENV === 'production') throw new StorageError('Supabase Storage is required in production (SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY)');
  return createLocalStorage({ dir: config.GAMES_LOCAL_DIR, bucket: config.SUPABASE_GAMES_BUCKET });
}

/** The `clips` bucket (GIFs, screenshots): public in Supabase, local disk in development. */
export function createClipStorage(
  config: Pick<Config, 'NODE_ENV' | 'SUPABASE_URL' | 'SUPABASE_SERVICE_ROLE_KEY' | 'SUPABASE_CLIPS_BUCKET' | 'CLIPS_LOCAL_DIR'>,
): ObjectStorage {
  if (config.SUPABASE_URL && config.SUPABASE_SERVICE_ROLE_KEY)
    return createSupabaseStorage({
      url: config.SUPABASE_URL,
      serviceKey: config.SUPABASE_SERVICE_ROLE_KEY,
      bucket: config.SUPABASE_CLIPS_BUCKET,
      public: true,
    });
  if (config.NODE_ENV === 'production') throw new StorageError('Supabase Storage is required in production (SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY)');
  return createLocalStorage({ dir: config.CLIPS_LOCAL_DIR, bucket: config.SUPABASE_CLIPS_BUCKET });
}
